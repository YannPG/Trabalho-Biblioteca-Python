class Livro:
    def __init__(self, codigo_livro, titulo, codigo_autor, codigo_categoria, ano_publicacao, disponibilidade):
        self.codigo_livro = codigo_livro
        self.titulo = titulo
        self.codigo_autor = codigo_autor 
        self.codigo_categoria = codigo_categoria 
        self.ano_publicacao = ano_publicacao 
        self.disponibilidade = disponibilidade